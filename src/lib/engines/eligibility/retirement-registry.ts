/** Normalize player name or ID to lookup key */
export function normalizePlayerLookupKey(idOrName: string): string {
  return idOrName
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '-');
}

/**
 * Searches the verified retirement registry for a player record.
 */
export function getVerifiedRetirementRecord(
  playerId: string,
  playerName?: string
): VerifiedRetirementEntry | undefined {
  const slug = normalizePlayerLookupKey(playerId);
  if (VERIFIED_RETIREMENT_REGISTRY[slug]) {
    return VERIFIED_RETIREMENT_REGISTRY[slug];
  }

  if (playerName) {
    const nameSlug = normalizePlayerLookupKey(playerName);
    if (VERIFIED_RETIREMENT_REGISTRY[nameSlug]) {
      return VERIFIED_RETIREMENT_REGISTRY[nameSlug];
    }

    // Exact canonical-name matching only. The previous substring match meant short
    // slugs (e.g. "a-singh") could be mapped to an unrelated retired player.
    const lower = playerName.trim().toLowerCase();
    for (const entry of Object.values(VERIFIED_RETIREMENT_REGISTRY)) {
      if (entry.canonicalName.toLowerCase() === lower) {
        return entry;
      }
    }
  }

  return undefined;
}
